#!/bin/bash

echo "╔════════════════════════════════════════════════════╗
║                                                    ║
║  ️ ➡️ Create .env file                              ║
║                                                    ║
╚════════════════════════════════════════════════════╝"
if [ ! -f .env ]; then
    cp .env.example .env
    echo "✓ .env file created"
else
    echo "⊘ .env file already exists, skipping..."
fi

# -------------------------------------------------------------------------------- #

echo "╔════════════════════════════════════════════════════╗
║                                                    ║
║  ️ ➡️ Installing vendor/                            ║
║                                                    ║
╚════════════════════════════════════════════════════╝"
if [ ! -d vendor ] || [ -z "$(ls -A vendor)" ]; then
    composer install --ignore-platform-reqs
    echo "✓ Vendor installed"
else
    echo "⊘ Vendor already exists and is not empty, skipping..."
fi

# -------------------------------------------------------------------------------- #

echo "╔════════════════════════════════════════════════════╗
║                                                    ║
║  ️ ➡️ Installing node_modules/                      ║
║                                                    ║
╚════════════════════════════════════════════════════╝"
yarn install

# -------------------------------------------------------------------------------- #

echo "╔════════════════════════════════════════════════════╗
║                                                    ║
║  ️ ➡️ Create APP_KEY 'php artisan key:generate'     ║
║                                                    ║
╚════════════════════════════════════════════════════╝"
if grep -q "APP_KEY=$" .env || ! grep -q "APP_KEY=" .env; then
    php artisan key:generate
    echo "✓ APP_KEY generated"
else
    echo "⊘ APP_KEY is already set, skipping..."
fi

# -------------------------------------------------------------------------------- #

echo "╔════════════════════════════════════════════════════╗
║                                                    ║
║  ️ ➡️ Run migrations                                ║
║                                                    ║
╚════════════════════════════════════════════════════╝"
php artisan migrate

# -------------------------------------------------------------------------------- #

echo "╔════════════════════════════════════════════════════╗
║                                                    ║
║  ️ ➡️ Install Filament assets                       ║
║                                                    ║
╚════════════════════════════════════════════════════╝"
php artisan filament:assets

# -------------------------------------------------------------------------------- #

echo "╔════════════════════════════════════════════════════╗
║                                                    ║
║  ️ ➡️ Building assets                               ║
║                                                    ║
╚════════════════════════════════════════════════════╝"
yarn build
